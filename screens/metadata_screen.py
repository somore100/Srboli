    # ── analysis ──────────────────────────────────────────────────────────
    def _analyse(self, path):
        self._path = path
        name = os.path.basename(path)
        self._file_lbl.text = name
        self._verdict_lbl.text = "Analysing..."
        self._verdict_lbl.color = (0.7, 0.7, 0.7, 1)
        self._find_grid.clear_widgets()
        self._meta_grid.clear_widgets()

        ext = os.path.splitext(path)[1].lower()
        self._edit_btn.disabled = not (HAS_PIL and ext in EDITABLE_EXTS)
        if ext in IMAGE_EXTS:
            # images can be shown straight away, no extraction needed
            self._preview_img.source = path
            self._preview_img.reload()
        else:
            self._preview_img.source = ""

        def _run():
            if ext in IMAGE_EXTS:
                meta = _extract_image_meta(path)
                thumb = None
            elif ext in VIDEO_EXTS:
                meta = _extract_video_meta(path)
                thumb = _video_thumb(path)
            else:
                meta = {"Error": "Unsupported file type"}
                thumb = None

            findings = _analyse_ai(meta)
            level, verdict_text = _verdict(findings)

            def _apply(dt):
                if self._path != path:
                    return  # a different file was picked while this ran
                self._meta     = meta
                self._findings = findings
                if thumb and os.path.exists(thumb):
                    self._preview_img.source = thumb
                    self._preview_img.reload()
                self._show_results(meta, findings, level, verdict_text)

            Clock.schedule_once(_apply, 0)

        threading.Thread(target=_run, daemon=True).start()

    def _show_results(self, meta, findings, level, verdict_text):
        # verdict
        self._verdict_lbl.text  = verdict_text
        self._verdict_lbl.color = LEVEL_COLORS.get(level, (1,1,1,1))

        # findings
        self._find_grid.clear_widgets()
        for flevel, reason in findings:
            tag = {"red":"[RED]","yellow":"[?]","green":"[OK]"}.get(flevel,"")
            lbl = Label(
                text=f"{tag}  {reason}",
                size_hint_y=None, height=dp(22),
                font_size=11, halign="left",
                color=LEVEL_COLORS.get(flevel, (1,1,1,1)))
            lbl.bind(size=lbl.setter("text_size"))
            self._find_grid.add_widget(lbl)

        if not findings:
            self._find_grid.add_widget(Label(
                text="No indicators found.", size_hint_y=None, height=dp(22),
                font_size=11))

        # metadata table
        self._meta_grid.clear_widgets()
        for k, v in sorted(meta.items()):
            key_lbl = Label(
                text=k, size_hint_y=None, height=dp(22),
                font_size=11, bold=True, halign="left",
                color=(0.7, 0.85, 1, 1))
            key_lbl.bind(size=key_lbl.setter("text_size"))
            val_lbl = Label(
                text=str(v), size_hint_y=None,
                font_size=11, halign="left", valign="top")
            val_lbl.bind(
                width=lambda inst, w: setattr(inst, "text_size", (w, None)))
            val_lbl.bind(
                texture_size=lambda inst, ts: setattr(
                    inst, "height", max(dp(22), ts[1])))
            self._meta_grid.add_widget(key_lbl)
            self._meta_grid.add_widget(val_lbl)

    # ── export ────────────────────────────────────────────────────────────
    def _copy_meta(self, *a):
        if not self._meta:
            return
        text = "\n".join(f"{k}: {v}" for k, v in sorted(self._meta.items()))
        Clipboard.copy(text)

    def _export_json(self, *a):
        if not self._meta or not self._path:
            return
        base, _ext = os.path.splitext(self._path)
        out_path = base + "_metadata.json"
        data = {
            "file":     self._path,
            "metadata": self._meta,
            "findings": [{"level": f[0], "reason": f[1]}
                         for f in self._findings],
        }
        try:
            with open(out_path, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
            Popup(title="Exported",
                  content=Label(text=f"Saved:\n{out_path}"),
                  size_hint=(0.75, 0.35)).open()
        except Exception as e:
            Popup(title="Error", content=Label(text=str(e)),
                  size_hint=(0.65, 0.3)).open()

