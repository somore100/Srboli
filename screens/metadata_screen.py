    # ── file picker ───────────────────────────────────────────────────────
    def _pick_file(self, *a):
        chooser = FileChooserIconView(
            path=os.path.expanduser("~"), multiselect=False)
        btn = Button(text="Inspect this file", size_hint_y=None, height=dp(44))
        layout = BoxLayout(orientation="vertical")
