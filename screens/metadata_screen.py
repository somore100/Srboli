IMAGE_EXTS = {".jpg",".jpeg",".png",".bmp",".gif",".webp",".tiff",".tif"}
VIDEO_EXTS = {".mp4",".mkv",".avi",".mov",".wmv",".flv",".webm",".m4v"}

# Formats Pillow can reliably write EXIF back to. TIFF deliberately left
# out here even though it can technically carry EXIF - it uses its own
# tag-writing path (tiffinfo) rather than the generic exif= kwarg, and
# getting that wrong risks silently corrupting the file, so it's not
# worth the risk without being able to verify it thoroughly.
EDITABLE_EXTS = {".jpg", ".jpeg", ".png", ".webp"}

# tag name -> numeric EXIF tag id, for the fields we let you edit.
# Make/Model/Software/Artist/Copyright/DateTime live on the main IFD.
# DateTimeOriginal lives in the Exif sub-IFD (0x8769) instead - handled
# separately since it needs get_ifd(), and older Pillow versions can be
# unreliable writing to it, so that one field degrades gracefully.
EDITABLE_TAGS = {
    "Make": 271, "Model": 272, "Software": 305,
    "Artist": 315, "Copyright": 33432, "DateTime": 306,
}
EXIF_IFD_TAG = 0x8769          # sub-IFD holding DateTimeOriginal etc.
DATETIME_ORIGINAL_TAG = 36867
GPS_IFD_TAG = 0x8825

# ── AI indicator rules ────────────────────────────────────────────────────────
# Each rule: (field, pattern, flag_level, reason)
# flag_level: "green"=clean, "yellow"=suspicious, "red"=red flag
AI_RULES = [
    # Software signatures
    ("Software", r"(?i)stable.diffusion|midjourney|dall.?e|imagen|"
                 r"firefly|leonardo|runway|kling|sora|pika|gen-2|"
                 r"civitai|automatic1111|comfyui|invokeai|diffusers",
     "red", "Known AI generation software detected in metadata"),
    ("Software", r"(?i)adobe.photoshop|lightroom|gimp|affinity",
     "green", "Known photo editor (not AI-specific)"),
    ("ProcessingSoftware", r"(?i)stable.diffusion|midjourney|dall.?e",
     "red", "AI processing software in metadata"),
    # Missing camera info
    ("Make", r"^$", "yellow", "No camera make recorded"),
    ("Model", r"^$", "yellow", "No camera model recorded"),
    # Suspicious creation tools
    ("Creator", r"(?i)ai|bot|generated|synthetic|fake",
     "red", "Creator field suggests AI generation"),
    ("Description", r"(?i)generated by|created by ai|prompt:|negative prompt:",
     "red", "Description contains AI generation language"),
    ("Comment", r"(?i)prompt:|steps:|cfg.?scale:|sampler:|seed:",
     "red", "Comment contains AI generation parameters"),
    # PNG specific (SD often writes here)
    ("parameters", r"(?i)steps:|cfg|sampler|seed|negative",
     "red", "PNG parameters chunk contains Stable Diffusion settings"),
    # Dates
    ("DateTimeOriginal", r"^$", "yellow", "No original capture date"),
    # GPS
    ("GPSInfo", r"^$", "yellow", "No GPS data (not conclusive alone)"),
]

# Known clean camera makes
CAMERA_MAKES = {"canon","nikon","sony","fujifilm","olympus","panasonic",
                "leica","hasselblad","pentax","ricoh","apple","samsung",
                "google","huawei","xiaomi","oppo","motorola","lg"}

def _extract_image_meta(path):
    """Returns dict of metadata fields from image."""
    meta = {}
    if not HAS_PIL:
        return meta
    try:
        img = PILImage.open(path)
        meta["Format"]    = img.format or "Unknown"
        meta["Mode"]      = img.mode
        meta["Size"]      = f"{img.width} x {img.height} px"
        meta["File size"] = _fmt_size(os.path.getsize(path))

        # EXIF
        exif_raw = img._getexif() if hasattr(img, "_getexif") else None
        if exif_raw:
            for tag_id, val in exif_raw.items():
                tag = TAGS.get(tag_id, str(tag_id))
                if isinstance(val, bytes):
                    try: val = val.decode("utf-8", errors="replace")
                    except: val = repr(val)
                meta[tag] = str(val)[:300]
        else:
            meta["EXIF"] = "None found"

        # PNG text chunks (Stable Diffusion stores prompts here)
        if hasattr(img, "text") and img.text:
            for k, v in img.text.items():
                meta[f"PNG:{k}"] = str(v)[:500]

        # XMP
        if hasattr(img, "info"):
            for k, v in img.info.items():
                if k not in ("exif",) and isinstance(v, (str, int, float)):
                    meta[f"Info:{k}"] = str(v)[:200]
    except Exception as e:
        meta["Error"] = str(e)
    return meta

def _extract_video_meta(path):
    """Returns dict of metadata from video using cv2 + ffprobe if available."""
    meta = {}
    meta["File size"] = _fmt_size(os.path.getsize(path))
    meta["Format"]    = os.path.splitext(path)[1].upper().lstrip(".")

    if HAS_CV2:
        try:
            cap = cv2.VideoCapture(path)
            fps   = cap.get(cv2.CAP_PROP_FPS)
            total = cap.get(cv2.CAP_PROP_FRAME_COUNT)
            w     = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            h     = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
            cap.release()
            dur = total / fps if fps else 0
            meta["Resolution"] = f"{w} x {h} px"
            meta["Duration"]   = _fmt_dur(dur)
            meta["FPS"]        = f"{fps:.2f}"
            meta["Frames"]     = str(int(total))
        except Exception as e:
            meta["cv2 error"] = str(e)

    # ffprobe for rich metadata
    try:
        result = subprocess.run(
            ["ffprobe", "-v", "quiet", "-print_format", "json",
             "-show_format", "-show_streams", path],
            capture_output=True, text=True, timeout=8)
        if result.returncode == 0:
            data = json.loads(result.stdout)
            fmt  = data.get("format", {})
            tags = fmt.get("tags", {})
            for k, v in tags.items():
                meta[f"Tag:{k}"] = str(v)[:300]
            meta["Bit rate"] = fmt.get("bit_rate", "?")
            # streams
            for i, stream in enumerate(data.get("streams", [])):
                t = stream.get("codec_type","?")
                c = stream.get("codec_name","?")
                meta[f"Stream {i} ({t})"] = c
                st = stream.get("tags", {})
                for k, v in st.items():
                    meta[f"Stream{i}:{k}"] = str(v)[:200]
    except FileNotFoundError:
        meta["ffprobe"] = "Not installed (apt install ffmpeg)"
    except Exception as e:
        meta["ffprobe error"] = str(e)

    return meta

def _video_thumb(path):
    """Grab a single frame from a video so it can be previewed too."""
    if not (HAS_CV2 and HAS_PIL):
        return None
    try:
        cache = app_data.subdir("metadata_cache")
        name  = f"mt_{abs(hash(path))}.jpg"
        thumb = os.path.join(cache, name)
        if os.path.exists(thumb):
            return thumb
        cap   = cv2.VideoCapture(path)
        total = cap.get(cv2.CAP_PROP_FRAME_COUNT)
        cap.set(cv2.CAP_PROP_POS_FRAMES, max(0, int(total * 0.05)))
        ok, frame = cap.read()
        cap.release()
        if ok:
            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            PILImage.fromarray(rgb).save(thumb, "JPEG", quality=82)
            return thumb
    except Exception:
        pass
    return None


def _analyse_ai(meta):
    """
    Returns list of (level, reason) tuples.
    Levels: "green", "yellow", "red"
    """
    findings = []
    make = meta.get("Make", "").lower()

    # Check camera make first
    if make:
        if any(m in make for m in CAMERA_MAKES):
            findings.append(("green",
                f"Camera make recognised: {meta['Make']}"))
        else:
            findings.append(("yellow",
                f"Unknown camera make: {meta['Make']}"))
    else:
        findings.append(("yellow", "No camera make (could be screenshot/AI)"))

    # Run all rules
    for field, pattern, level, reason in AI_RULES:
        val = None
        fl = field.lower()
        # exact key match first, so e.g. field "Model" doesn't accidentally
        # pick up the value of an unrelated "LensModel" tag
        for k, v in meta.items():
            if k.lower() == fl:
                val = str(v)
                break
        if val is None:
            # fall back to substring match, needed for prefixed keys like
            # "PNG:parameters" or "Stream0:codec"
            for k, v in meta.items():
                if fl in k.lower():
                    val = str(v)
                    break
        val = val or ""
        if pattern == r"^$":
            if not val:
                findings.append((level, reason))
        else:
            if re.search(pattern, val):
                findings.append((level, reason))

    # Video-specific: no tags at all = suspicious
    if not any(k.startswith("Tag:") for k in meta):
        if meta.get("Format","") in ("MP4","MKV","WEBM","MOV"):
            findings.append(("yellow",
                "No metadata tags in video container"))

    # PNG with no EXIF but has PNG text = very suspicious (SD pattern)
    if any(k.startswith("PNG:") for k in meta):
        findings.append(("red",
            "PNG text chunks present — common in AI-generated images"))

    return findings

def _verdict(findings):
    levels = [f[0] for f in findings]
    reds    = levels.count("red")
    yellows = levels.count("yellow")
    greens  = levels.count("green")
    if reds >= 2:
        return "red", "HIGH RISK — likely AI generated"
    elif reds == 1:
        return "red", "RED FLAG — strong AI indicator found"
    elif yellows >= 3:
        return "yellow", "SUSPICIOUS — multiple weak indicators"
    elif yellows >= 1 and greens == 0:
        return "yellow", "SUSPICIOUS — missing expected camera data"
    elif greens >= 1 and reds == 0 and yellows <= 1:
        return "green", "LIKELY REAL — camera metadata present"
    else:
        return "yellow", "UNCERTAIN — mixed signals"

def _fmt_size(b):
    if b < 1024: return f"{b} B"
    elif b < 1048576: return f"{b/1024:.1f} KB"
    elif b < 1073741824: return f"{b/1048576:.1f} MB"
    return f"{b/1073741824:.2f} GB"

def _fmt_dur(s):
    s = int(s); h = s//3600; m=(s%3600)//60; sc=s%60
    return f"{h}:{m:02d}:{sc:02d}" if h else f"{m}:{sc:02d}"

